#!/bin/bash
cd /
pwd
ls -la

# MYSQL_USER/MYSQL_PASSWORD/MYSQL_DATABASE sont injectées directement par Docker Compose
# (voir environment: du service php) - jamais lues depuis un fichier .env copié dans
# l'image, pour ne pas figer de secrets dans une couche d'image immuable.
if [ -z "${MYSQL_USER:-}" ] || [ -z "${MYSQL_PASSWORD:-}" ] || [ -z "${MYSQL_DATABASE:-}" ]; then
    echo "Erreur : MYSQL_USER, MYSQL_PASSWORD et MYSQL_DATABASE doivent être fournies en variables d'environnement (voir docker-compose.yml)."
    exit 1
fi

# Create or update the PHP config file
cat > config.php << EOF
<?php
// Generated by generate_db_config while building docker file
\$dbservername = "db";
\$dbusername = "${MYSQL_USER}";
\$dbpassword = "${MYSQL_PASSWORD}";
\$dbname = "${MYSQL_DATABASE}";
?>
EOF

echo "Config file generated successfully!"
mv config.php /var/www/html/SwitchBoard/SwitchBoard/config/config.php